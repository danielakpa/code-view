"""Database models for persistent runner and sandbox records."""

# Generate timestamps.
from datetime import datetime, timezone

# Generate and validate unique IDs.
from uuid import UUID, uuid4

# Define structured API data.
from pydantic import BaseModel, Field

# SQLAlchemy database column types.
from sqlalchemy import DateTime, Integer, String
from sqlalchemy.dialects.postgresql import UUID as PostgreSQLUUID
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class RunnerSession(BaseModel):
    """Represent a developer session managed by FastAPI."""

    # Unique ID created by Django.
    session_id: UUID

    # Developer who owns the session.
    developer_id: int = Field(gt=0)

    # Private group containing the developer.
    group_id: int = Field(gt=0)

    # Current runner lifecycle state.
    status: str = "registered"

    # Time the runner registered this session.
    created_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )

    # Time the session was last updated.
    updated_at: datetime = Field(
        default_factory=lambda: datetime.now(timezone.utc)
    )


class Base(DeclarativeBase):
    """Base class used to define SQLAlchemy database tables."""

    pass


class RunnerSessionRecord(Base):
    """Store a runner-managed terminal session in PostgreSQL."""

    # Store the table inside the runner schema.
    __tablename__ = "runner_sessions"
    __table_args__ = {"schema": "runner"}

    # Unique terminal session ID generated by Django.
    session_id: Mapped[UUID] = mapped_column(
        PostgreSQLUUID(as_uuid=True),
        primary_key=True,
    )

    # Developer who owns the terminal session.
    developer_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # Private group containing the developer.
    group_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # Current runner session state.
    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="registered",
    )

    # Time the session was registered.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    # Time the session was last updated.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )


class SandboxRecord(Base):
    """Store persistent developer sandbox information."""

    # Store the sandbox table inside the runner schema.
    __tablename__ = "sandboxes"
    __table_args__ = {"schema": "runner"}

    # Unique sandbox identifier.
    sandbox_id: Mapped[UUID] = mapped_column(
        PostgreSQLUUID(as_uuid=True),
        primary_key=True,
        default=uuid4,
    )

    # Developer who owns the sandbox.
    developer_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # CodeView group associated with the sandbox.
    group_id: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    # Current sandbox lifecycle status.
    status: Mapped[str] = mapped_column(
        String(20),
        nullable=False,
        default="prepared",
    )

    # Time the sandbox record was created.
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
    )

    # Time the sandbox record was last updated.
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        default=lambda: datetime.now(timezone.utc),
        onupdate=lambda: datetime.now(timezone.utc),
    )